//! Strict framing for the opt-in mTLS identity profile, separate from legacy DER.
//! Extract only the actual RFC5280 SubjectPublicKeyInfo, never search for key bytes.

use super::{ED25519_OID_TLV, spki_content_ed25519_raw};

struct Der<'a>(&'a [u8]);
impl<'a> Der<'a> {
    fn take(&mut self, tag: u8) -> Result<&'a [u8], String> {
        let data = self.0;
        if data.first() != Some(&tag) {
            return Err("certificate: unexpected DER tag".into());
        }
        let length = *data.get(1).ok_or("certificate: truncated DER")?;
        let (header, size) = if length < 128 {
            (2usize, usize::from(length))
        } else {
            let count = usize::from(length & 127);
            if count == 0 || count > 4 || data.get(2) == Some(&0) {
                return Err("certificate: noncanonical DER length".into());
            }
            let lengths = data
                .get(2..2 + count)
                .ok_or("certificate: truncated DER length")?;
            let mut size = 0usize;
            for byte in lengths {
                size = size
                    .checked_mul(256)
                    .and_then(|n| n.checked_add(usize::from(*byte)))
                    .ok_or("certificate: DER overflow")?;
            }
            if size < 128 {
                return Err("certificate: noncanonical DER length".into());
            }
            (2 + count, size)
        };
        let end = header
            .checked_add(size)
            .ok_or("certificate: DER overflow")?;
        let value = data
            .get(header..end)
            .ok_or("certificate: truncated DER value")?;
        self.0 = &data[end..];
        Ok(value)
    }
    fn done(&self) -> Result<(), String> {
        if self.0.is_empty() {
            Ok(())
        } else {
            Err("certificate: trailing DER".into())
        }
    }
}
fn algorithm(bytes: &[u8]) -> Result<(), String> {
    if bytes != ED25519_OID_TLV {
        return Err("certificate: expected Ed25519 algorithm".into());
    }
    Ok(())
}

pub(super) fn strict_cert_peer(bytes: &[u8]) -> Result<[u8; 32], String> {
    let mut outer = Der(bytes);
    let mut certificate = Der(outer.take(0x30)?);
    outer.done()?;
    let mut tbs = Der(certificate.take(0x30)?);
    // Supported profile is v3, as generated by rcgen; no optional implicit version.
    if tbs.take(0xa0)? != [0x02, 0x01, 0x02] {
        return Err("certificate: unsupported version".into());
    }
    if tbs.take(0x02)?.is_empty() {
        return Err("certificate: empty serial".into());
    }
    algorithm(tbs.take(0x30)?)?;
    tbs.take(0x30)?; // issuer Name, fixed RFC5280 position
    let mut validity = Der(tbs.take(0x30)?);
    for _ in 0..2 {
        let tag = *validity.0.first().ok_or("certificate: missing validity")?;
        if tag != 0x17 && tag != 0x18 {
            return Err("certificate: invalid validity tag".into());
        }
        validity.take(tag)?;
    }
    validity.done()?;
    tbs.take(0x30)?; // subject Name, fixed RFC5280 position
    let spki = tbs.take(0x30)?;
    // Validate the complete SPKI envelope, including no suffix after the key.
    let mut parsed = Der(spki);
    algorithm(parsed.take(0x30)?)?;
    let key = parsed.take(0x03)?;
    if key.len() != 33 || key[0] != 0 {
        return Err("certificate: invalid Ed25519 key".into());
    }
    parsed.done()?;
    // rcgen may append [3] extensions, but not extra SPKIs/ambiguous fields.
    if !tbs.0.is_empty() {
        let mut extensions = Der(tbs.take(0xa3)?);
        extensions.take(0x30)?;
        extensions.done()?;
    }
    tbs.done()?;
    algorithm(certificate.take(0x30)?)?;
    let signature = certificate.take(0x03)?;
    if signature.len() != 65 || signature[0] != 0 {
        return Err("certificate: invalid Ed25519 signature framing".into());
    }
    certificate.done()?;
    spki_content_ed25519_raw(spki)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::FabricIdentity;
    #[test]
    fn strict_identity_extracts_only_actual_spki_and_rejects_suffix() {
        let id = FabricIdentity::from_ed25519_seed([29; 32]).unwrap();
        assert_eq!(
            strict_cert_peer(&id.inner.cert_der).unwrap(),
            id.peer_id().0
        );
        let mut extra = id.inner.cert_der.clone();
        extra.extend_from_slice(&id.peer_id().0);
        assert!(strict_cert_peer(&extra).is_err());
        for len in 0..id.inner.cert_der.len() {
            assert!(strict_cert_peer(&id.inner.cert_der[..len]).is_err());
        }
    }
    #[test]
    fn oid_and_key_outside_spki_do_not_authenticate() {
        let id = FabricIdentity::from_ed25519_seed([31; 32]).unwrap();
        let mut cert = id.inner.cert_der.clone();
        // Flip the SPKI algorithm to X25519 while leaving the outer Ed25519
        // signature algorithms and an embedded admitted key unchanged.
        let positions: Vec<_> = cert
            .windows(5)
            .enumerate()
            .filter(|(_, p)| *p == ED25519_OID_TLV)
            .map(|(i, _)| i)
            .collect();
        assert_eq!(positions.len(), 3);
        cert[positions[1] + 4] = 0x6e;
        assert!(strict_cert_peer(&cert).is_err());
    }
}
